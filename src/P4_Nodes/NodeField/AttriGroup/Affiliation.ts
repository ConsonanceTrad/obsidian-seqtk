/**
 * 从属关系簇（affiliation）
 *
 * 框架 / 事务 / 证据节点之间通过**上级的 follows** 单向建立从属：上级记录「有向直属下属」，
 * 下级不再写 parent 字段。如此一个节点可以同时挂在多个上级下（多归属），也不会出现
 * 「父子两边各存一份、改一边就不同步」的问题。反查上级走 follows 入边（GET_Parents）。
 * 其余字段为扩展关系，按簇语义组合到具体节点类型时再收窄适用面。
 *
 * 本簇只声明"字段存在性与形状"，不决定某个 kind 是否拥有它——
 * 是否组合由 Nodes/* 的节点类型接口决定（本次不动）。
 */

export interface AffiliationFields {
    /** 有向直属下属（nodeId 列表）—— 上级标注其直属下级；**归属的唯一权威来源** */
    follows?: string[];
    /**
     * 有向直属上级（nodeId）—— 已废弃，不再写入也不再读回（见 GET_Parents 的说明）
     *
     * 留在类型上只为兼容旧文件里已有的字段：解析时原样忽略，不影响归属判定。
     */
    parent?: string;
    /** 无向关联（nodeId 列表）—— 互相引用的对等关系 */
    links?: string[];
    /** 标记插入（nodeId 列表）—— 由插入的标记节点记录其宿主链 */
    progress?: string[];
}
